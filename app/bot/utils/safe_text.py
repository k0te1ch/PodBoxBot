"""Чужой текст в сообщениях бота: только через маскировку секретов.

Отчёты об ошибках и логи маскирует SDK. Но бот и сам пишет админам: текст
исключения в статусе выпуска, ответ FTP, ошибку публишера из Kafka, адрес
ленты RSS. Всё, что пришло из исключения или от внешней системы, перед
вставкой в сообщение проходит через эти функции.
"""

from html import escape

from sagenza_tgbot_sdk.masking import mask_secrets


def safe_text(value: object) -> str:
    """Текст исключения или ответа внешней системы без секретов."""
    return mask_secrets(str(value))


def safe_html(value: object) -> str:
    """То же для HTML-сообщения. Маскировка идёт до экранирования: после
    него ``&`` и кавычки в секрете уже не совпали бы с зарегистрированным."""
    return escape(safe_text(value))
